/**
 * Los píxeles (RGBA) del QR dibujado en negro sobre blanco, con `escala` píxeles por módulo y los 4 módulos de margen
 * que lleva un QR impreso.
 */
export function pixelesDelQr(escala: number): { data: Uint8ClampedArray; lado: number } {
  const modulos = QR_DE_MESA.filas.length
  const margen = 4
  const lado = (modulos + margen * 2) * escala
  const data = new Uint8ClampedArray(lado * lado * 4).fill(255)
  for (let y = 0; y < lado; y++) {
    for (let x = 0; x < lado; x++) {
      const fila = QR_DE_MESA.filas[Math.floor(y / escala) - margen]
      if (fila?.[Math.floor(x / escala) - margen] !== '1') continue
      const i = (y * lado + x) * 4
      data[i] = 0
      data[i + 1] = 0
      data[i + 2] = 0
    }
  }
  return { data, lado }
}
